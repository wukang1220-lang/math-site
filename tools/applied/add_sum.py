done = set()
for b in range(1, 7):
    p = os.path.join(HERE, 'content', f'b{b}.txt')
    lines = open(p, encoding='utf-8').read().split('\n')
    out = []
    for i, ln in enumerate(lines):
        if ln.startswith('sum:'):
            continue
        out.append(ln)
        m = re.match(r'@ (\S+)', ln)
        if m:
            out.append('sum: ' + SUM[m.group(1)])
            done.add(m.group(1))
    open(p, 'w', encoding='utf-8').write('\n'.join(out))
